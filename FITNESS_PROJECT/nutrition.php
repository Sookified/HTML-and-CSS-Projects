<p style="color:white; font-size:20px">The purpose of this article is to give the beginner a simple, uncomplicated approach to eating and exercising with the goal of losing body fat. A beginner is defined as someone with 2-4 months training experience, or someone who's been training longer but feels they haven't been making good progress.<br /><br />

Want to lose body fat? The first thing I'm going to tell you is, don't go on a diet. That's right, going on a diet is the biggest mistake you can make. <br /><br />

Why? Because most diets are not based on sound nutritional principles, are hard to follow, and most of all, make no long term provision for maintaining your weight loss. In other words, when you go on a diet, you eventually go off the diet and do what? Go right back to the eating habits that caused the weight gain in the first place. Besides, some of these diet ideas are way out there.</p>

