<p style="color:white; font-size:20px; padding-left:20px; padding-right:20px">Before we go further, let me define something. There's a definite difference between losing weight and losing fat. Most people don't understand that to lose weight means to lose muscle, water and fat. That's not what we want. What we want is to lose fat and keep the muscle. Muscle requires more calories to maintain it, and that means a better supported metabolism, so there's a definite advantage to building more muscle.</b></p> <br />

<p style="color:white; font-size:20px; padding-left:20px; padding-right:20px">So if going on a diet doesn't work, what does? The answer is to make healthy lifestyle changes you can live with. This refers to both your eating habits and your activity level. Right off the bat, you want to dramatically decrease your sugar, or simple carb intake, and your fat intake.</p><br /><br />

<p style="color:white; font-size:20px; padding-left:20px; padding-right:20px">High protein, moderate carb (mostly slow or complex carbs), and low fat is the way to go. As well, you want to eat 5-6 small meals a day, not 3 big ones (or worse yet, starve yourself on 1-2 meals). You also have to add a cardio program. Fat loss is not only a function of calories in/calories out but also the type of calories and the timing of those calories and you must be burning more calories through physical activity than you are taking in.</p><br />

<p style="text-align:center; font-size:30px; text-transform:uppercase; color:#ffcd2c">
<b>Food Serves A Very Functional Purpose</b></p>

<p style="color:white; font-size:20px; padding-left:20px; padding-right:20px"> It's not here just for taste, although most people see taste as the sole point. Many of us, myself included, grew up eating nothing but junk and never knowing anything about nutrition. I never heard the terms "protein" "carbs" or "fat" as a kid. And in those days, they didn't have nutrition panels on food labels.
</p> <br />
<p style="color:white; font-size:20px; padding-left:20px; padding-right:20px">
Ignorance of what people eat is why there are so many over weight people today. The food industry hasn't helped, look at what's out there - fast food, junk food, processed food, it's no wonder so many people have a hard time with their weight.

The function of food is to supply energy and nutrients to the body, eating for taste is secondary. That doesn't mean you shouldn't enjoy the taste of what you eat, but an understanding of what you should eat will lead you to make better choices.
</p>
<br />
<p style="color:white; font-size:20px; padding-left:20px; padding-right:20px">Food consists of three macro nutrients:

    Protein
    Carbohydrates
    Fats

Your body, after water, is mostly made of protein. You require protein every day, it performs literally thousands of functions in the body. It does this in the form of different combinations of amino acids, the "building blocks" of protein.

Carbohydrates are the preferred form of fuel for the body's energy needs. Simple or sugary carbs have there place but for the most part you should eat complex or slow burning carbs. An important point about carbs and where the average person makes there mistake is that after you supply your energy needs, any excess carbs will be stored as fat.

Think of this as similar to filling your car's gas tank - once the tank is full, if you keep pumping, you will have a lot of excess gas spilling out all over the place. Once your energy needs are met and you keep eating high carb meals, the excess "spills out" and you get fatter.

As for fat, there's good and bad types of fat, I will list what you should eat and what you should avoid later. Most of us eat way to much fat, primarily the bad types of fat, such as saturated fat and trans fat. Proper food choices/quantities can take care of this problem. So by reducing sugar, fat and total calorie consumption, we can control the food part of the equation, we'll cover the exercise part in a bit.</p>


